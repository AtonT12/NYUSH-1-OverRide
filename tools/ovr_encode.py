#!/usr/bin/env python3
"""Turn an OverRide SD recording into a C++ autonomous table.

The brain writes ``auton.bin`` during ``RunMode::Record``. Copy it off the SD
card and run:

    python tools/ovr_encode.py auton.bin

which rewrites ``src/auton/programs.cpp`` with the frames as a constexpr table.
Rebuild and download; the autonomous period now plays that run.

Run ``python tools/ovr_encode.py --selftest`` to verify the codec against the
same CRC vector and layout the C++ side uses.
"""

import argparse
import os
import struct
import sys
import zlib

MAGIC = b"OVRR"
VERSION = 1
HEADER_BYTES = 16
FRAME_BYTES = 12
MAX_FRAMES = 1500
FRAME_STRUCT = struct.Struct("<HhhhhBB")


def parse(data):
    if len(data) < HEADER_BYTES:
        raise ValueError("file shorter than the 16-byte header")
    if data[0:4] != MAGIC:
        raise ValueError("bad magic %r" % (data[0:4],))
    if data[4] != VERSION:
        raise ValueError("unsupported version %d" % data[4])

    period_ms, count, _reserved = struct.unpack_from("<HHH", data, 6)
    crc = struct.unpack_from("<I", data, 12)[0]

    if period_ms == 0:
        # The firmware falls back to 20 ms, so a zero here would make the table
        # play at a period its own header denies. Refuse it at the source.
        raise ValueError("control period is zero")
    if count > MAX_FRAMES:
        raise ValueError("frame count %d exceeds %d" % (count, MAX_FRAMES))
    payload = data[HEADER_BYTES:HEADER_BYTES + count * FRAME_BYTES]
    if len(payload) != count * FRAME_BYTES:
        raise ValueError("truncated: expected %d payload bytes, got %d"
                         % (count * FRAME_BYTES, len(payload)))
    if zlib.crc32(payload) & 0xFFFFFFFF != crc:
        raise ValueError("CRC mismatch: file is corrupt")

    frames = [FRAME_STRUCT.unpack_from(payload, i * FRAME_BYTES)
              for i in range(count)]

    previous = -1
    for index, frame in enumerate(frames):
        if frame[0] < previous:
            raise ValueError("timestamp goes backwards at frame %d" % index)
        previous = frame[0]
    return period_ms, frames


def build_blob(period_ms, frames):
    payload = b"".join(FRAME_STRUCT.pack(*frame) for frame in frames)
    header = bytearray(HEADER_BYTES)
    header[0:4] = MAGIC
    header[4] = VERSION
    struct.pack_into("<HHH", header, 6, period_ms, len(frames), 0)
    struct.pack_into("<I", header, 12, zlib.crc32(payload) & 0xFFFFFFFF)
    return bytes(header) + payload


def emit_cpp(path, frames, period_ms, source_name):
    lines = []
    lines.append("// Generated by tools/ovr_encode.py from %s." % source_name)
    lines.append("// Do not edit by hand; re-run the encoder instead.")
    lines.append("#include \"auton-programs.h\"")
    lines.append("")
    lines.append("namespace {")
    lines.append("")
    if frames:
        lines.append("const control::AutonFrame kFrames[] = {")
        for frame in frames:
            lines.append("    {%uu, %d, %d, %d, %d, %uu, %uu}," % frame)
        lines.append("};")
    else:
        lines.append("const control::AutonFrame kFrames[1] = {{0u, 0, 0, 0, 0, 0u, 0u}};")
    lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("namespace AutonPrograms {")
    lines.append("")
    lines.append("const control::AutonProgram kSelected(kFrames, %du, %du);"
                 % (len(frames), period_ms))
    lines.append("")
    lines.append("}  // namespace AutonPrograms")
    lines.append("")

    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))


def selftest():
    failures = 0

    def check(name, actual, expected):
        nonlocal failures
        if actual != expected:
            failures += 1
            print("FAIL %-40s actual=%r expected=%r" % (name, actual, expected))

    check("crc32 check vector", zlib.crc32(b"123456789") & 0xFFFFFFFF, 0xCBF43926)
    check("frame struct size", FRAME_STRUCT.size, FRAME_BYTES)

    frames = [
        (0, 0, 0, 0, 0, 0, 0),
        (500, 1000, -500, 250, 0, 1, 0),
        (1000, 0, 0, 0, 0, 0, 0),
    ]
    blob = build_blob(20, frames)
    check("blob size", len(blob), HEADER_BYTES + len(frames) * FRAME_BYTES)

    period_ms, parsed = parse(blob)
    check("period round trip", period_ms, 20)
    check("frame round trip", parsed, frames)

    corrupted = bytearray(blob)
    corrupted[HEADER_BYTES + 2] ^= 0xFF
    try:
        parse(bytes(corrupted))
    except ValueError:
        pass
    else:
        failures += 1
        print("FAIL corrupted payload was accepted")

    if failures == 0:
        print("selftest ok")
        return 0
    return 1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("recording", nargs="?", help="auton.bin from the SD card")
    parser.add_argument("--out", default=os.path.join("src", "auton", "programs.cpp"),
                        help="generated C++ file (default: src/auton/programs.cpp)")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()

    if args.selftest:
        return selftest()
    if not args.recording:
        parser.error("a recording path is required unless --selftest is used")

    with open(args.recording, "rb") as handle:
        data = handle.read()

    try:
        period_ms, frames = parse(data)
    except ValueError as error:
        print("error: %s" % error, file=sys.stderr)
        return 1

    duration = frames[-1][0] if frames else 0
    print("%d frames, %d ms, period %d ms" % (len(frames), duration, period_ms))
    emit_cpp(args.out, frames, period_ms, os.path.basename(args.recording))
    print("wrote %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
